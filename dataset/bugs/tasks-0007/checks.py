def _p(params):
    p = dict(PARAMS_DEFAULT)
    p.update(params or {})
    return p

def _open_and_rotate(dev, p, cycles):
    h.fresh(dev, APP, SEED)
    h.tap_text(dev, "Buy milk")
    for _ in range(cycles):
        dev.rotate(True); dev.wait_idle()
        dev.rotate(False); dev.wait_idle()

def _edit_shown(dev):
    return h.has(dev, "Buy milk") and not h.has(dev, "Pay rent"), {"texts": h.texts(dev)[:40]}

def _target(dev, p):
    _open_and_rotate(dev, p, 1)
    return _edit_shown(dev)

def _held(dev, p):
    _open_and_rotate(dev, p, 2)
    return _edit_shown(dev)

def _keep(dev, p):
    _open_and_rotate(dev, p, 0)
    return _edit_shown(dev)


def target(dev, params):
    return h.run(_target, dev, _p(params), TIER)


def held_out(dev, params):
    return h.run(_held, dev, _p(params), TIER)


def preserve(dev, params):
    return h.run(_keep, dev, _p(params), "A" if DB else "B")


CHECKS = {"target": target, "held_out": [held_out], "preservation": [preserve]}
